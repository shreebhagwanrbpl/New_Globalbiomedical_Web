export function getProductBySlug(slug: string): Product | undefined {
  if (!slug) return undefined;
  const normalized = slug.toLowerCase().trim();
  return staticProducts.find(p => p.slug.toLowerCase() === normalized);
}

export function getBestSellerProducts(): Product[] {
  return staticProducts.filter(p => p.bestSeller);
}

export function getNewArrivalProducts(): Product[] {
  return staticProducts.filter(p => p.newArrival);
}

export function getFeaturedProducts(): Product[] {
  return staticProducts.filter(p => p.featured);
}

export function getProductsByCategory(category: string): Product[] {
  if (!category || category === 'all') return staticProducts;
  return staticProducts.filter(p => p.category === category);
}
