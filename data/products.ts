export function getProductBySlug(slug: string): Product | undefined {
  return PRODUCTS.find(p => p.slug === slug || p.id === slug);
}

export function getProductById(id: string): Product | undefined {
  return PRODUCTS.find(p => p.id === id);
}

export function getProductsByCategory(categorySlug: string): Product[] {
  if (categorySlug === 'all') return PRODUCTS;
  return PRODUCTS.filter(p => p.category === categorySlug);
}

export function getFeaturedProducts(limit: number = 8): Product[] {
  return PRODUCTS.filter(p => p.featured || p.bestSeller).slice(0, limit);
}

export function getBestSellerProducts(limit: number = 8): Product[] {
  return PRODUCTS.filter(p => p.bestSeller).slice(0, limit);
}

export function getNewArrivalProducts(limit: number = 6): Product[] {
  return PRODUCTS.filter(p => p.newArrival).slice(0, limit);
}
