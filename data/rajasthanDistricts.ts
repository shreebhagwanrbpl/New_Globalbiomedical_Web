// Fast O(1) slug lookup map for all 780+ Indian districts
const allDistrictsMap = new Map<string, DistrictLocation>();

// 1. Add all 50 Rajasthan districts with deep local metadata
for (const d of RAJASTHAN_DISTRICTS) {
  allDistrictsMap.set(d.slug.toLowerCase(), d);
}

// 2. Add India major metros and medical centers
for (const d of INDIA_MAJOR_DISTRICTS) {
  allDistrictsMap.set(d.slug.toLowerCase(), d);
}

// 3. Add all remaining districts covering every State & UT of India (700+ total)
for (const d of ALL_OTHER_INDIA_DISTRICTS) {
  if (!allDistrictsMap.has(d.slug.toLowerCase())) {
    allDistrictsMap.set(d.slug.toLowerCase(), d);
  }
}

export const ALL_DISTRICTS: DistrictLocation[] = Array.from(allDistrictsMap.values());

export function getDistrictBySlug(slug: string): DistrictLocation | undefined {
  if (!slug) return undefined;
  const clean = slug.toLowerCase().trim().replace(/-district$/, '');
  return allDistrictsMap.get(clean) || allDistrictsMap.get(slug.toLowerCase().trim());
}

