// Aliases for common state slugs
const STATE_ALIASES: Record<string, string> = {
  'up': 'uttar-pradesh',
  'mp': 'madhya-pradesh',
  'wb': 'west-bengal',
  'tn': 'tamil-nadu',
  'ap': 'andhra-pradesh',
  'hp': 'himachal-pradesh',
  'jk': 'jammu-kashmir',
  'j-k': 'jammu-kashmir',
  'ncr': 'delhi',
  'delhi-ncr': 'delhi',
};

export function getStateBySlug(rawSlug: string): (StateData & { districts: DistrictLocation[] }) | undefined {
  if (!rawSlug) return undefined;
  const clean = rawSlug.toLowerCase().trim().replace(/-state$/, '');
  const slug = STATE_ALIASES[clean] || clean;

  const meta = ALL_STATES_META[slug];
  if (!meta) {
    // Check if any state name matches directly
    const foundStateKey = Object.keys(ALL_STATES_META).find(
      (k) => ALL_STATES_META[k].name.toLowerCase() === clean || k === clean
    );
    if (!foundStateKey) return undefined;
    return getStateBySlug(foundStateKey);
  }

  // Get all districts belonging to this state
  let districts: DistrictLocation[] = [];
  if (slug === 'rajasthan') {
    districts = RAJASTHAN_DISTRICTS;
  } else {
    districts = ALL_DISTRICTS.filter((d) => {
      const stateName = d.state ? d.state.toLowerCase() : '';
      return stateName === meta.name.toLowerCase() || (d.division && d.division.toLowerCase().includes(meta.name.toLowerCase()));
    });
  }

  return {
    ...meta,
    slug,
    districtsCount: districts.length,
    districts,
  };
}


